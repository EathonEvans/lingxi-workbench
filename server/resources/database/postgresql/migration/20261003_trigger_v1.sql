BEGIN;

-- ===== 定时触发器与主动运行 =====
-- 触发器绑定冻结的 Application/Agent/Workflow 已发布版本，绑定专属会话获得跨次执行记忆。
-- 全部关联均为逻辑外键，由 Service 事务校验归属、存在性与状态。

CREATE TABLE IF NOT EXISTS lingxi_core.ai_trigger
(
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                BIGINT       NOT NULL,
    application_id         BIGINT       NOT NULL,
    application_version_id BIGINT       NOT NULL,
    execution_mode         VARCHAR(16)  NOT NULL,
    agent_id               BIGINT,
    agent_version_id       BIGINT,
    workflow_id            BIGINT,
    workflow_version_id    BIGINT,
    conversation_id        BIGINT       NOT NULL,
    name                   VARCHAR(64)  NOT NULL,
    goal_template          TEXT         NOT NULL,
    cron_expr              VARCHAR(32)  NOT NULL,
    timezone               VARCHAR(32)  NOT NULL DEFAULT 'Asia/Shanghai',
    quiet_hours            VARCHAR(16),
    allowed_tool_codes     JSONB,
    status                 VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    next_fire_at           TIMESTAMPTZ  NOT NULL,
    last_run_id            VARCHAR(64),
    last_run_status        VARCHAR(32),
    last_run_at            TIMESTAMPTZ,
    consecutive_failures   INTEGER      NOT NULL DEFAULT 0,
    pause_reason           VARCHAR(64),
    deleted_at             TIMESTAMPTZ,
    created_at             TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at             TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_trigger_consecutive_failures CHECK (consecutive_failures >= 0)
);

COMMENT ON COLUMN lingxi_core.ai_trigger.quiet_hours IS '静默时段 HH:mm-HH:mm，落点在窗口内时顺延到窗口结束';
COMMENT ON COLUMN lingxi_core.ai_trigger.allowed_tool_codes IS '预授权工具码白名单；为空表示不预授权任何工具';

CREATE INDEX IF NOT EXISTS idx_trigger_due
    ON lingxi_core.ai_trigger (next_fire_at)
    WHERE status = 'ACTIVE' AND deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_trigger_user
    ON lingxi_core.ai_trigger (user_id, status);

CREATE TABLE IF NOT EXISTS lingxi_core.ai_trigger_fire
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trigger_id    BIGINT       NOT NULL,
    user_id       BIGINT       NOT NULL,
    planned_at    TIMESTAMPTZ  NOT NULL,
    fired_at      TIMESTAMPTZ,
    run_id        VARCHAR(64),
    status        VARCHAR(16)  NOT NULL,
    skip_reason   VARCHAR(32),
    error_message VARCHAR(256),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_trigger_fire_trigger
    ON lingxi_core.ai_trigger_fire (trigger_id, created_at DESC);

-- 主动运行复用顶级执行运行表，仅增加触发来源维度。
ALTER TABLE lingxi_core.ai_execution_run
    ADD COLUMN IF NOT EXISTS run_source VARCHAR(16) NOT NULL DEFAULT 'CHAT',
    ADD COLUMN IF NOT EXISTS trigger_id BIGINT,
    ADD COLUMN IF NOT EXISTS fire_id BIGINT;
CREATE INDEX IF NOT EXISTS idx_execution_run_trigger
    ON lingxi_core.ai_execution_run (trigger_id);

-- 会话消息增加来源标记；定时触发器产出的轮次以 TRIGGER 标识，前端渲染“定时任务”徽标。
ALTER TABLE lingxi_core.ai_conversation_message
    ADD COLUMN IF NOT EXISTS origin VARCHAR(16) NOT NULL DEFAULT 'CHAT';

COMMIT;
