BEGIN;

-- Agent草稿保存Skill选择；发布版本升级至V8后锁定精确SkillVersion。
ALTER TABLE lingxi_core.ai_agent_draft
    ADD COLUMN IF NOT EXISTS skill_ids JSONB NOT NULL DEFAULT '[]'::JSONB;
ALTER TABLE lingxi_core.ai_agent_draft
    DROP CONSTRAINT IF EXISTS ck_ai_agent_draft_schema_version,
    DROP CONSTRAINT IF EXISTS ck_ai_agent_draft_skill_ids;
UPDATE lingxi_core.ai_agent_draft SET schema_version = 8;
ALTER TABLE lingxi_core.ai_agent_draft
    ADD CONSTRAINT ck_ai_agent_draft_schema_version CHECK (schema_version = 8),
    ADD CONSTRAINT ck_ai_agent_draft_skill_ids CHECK (jsonb_typeof(skill_ids) = 'array');

-- 不创建物理外键；Service负责校验AgentVersion、Skill和SkillVersion归属与状态。
CREATE TABLE IF NOT EXISTS lingxi_core.ai_agent_version_skill
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_version_id     BIGINT      NOT NULL,
    skill_id             BIGINT      NOT NULL,
    skill_version_id     BIGINT      NOT NULL,
    skill_code           VARCHAR(64) NOT NULL,
    skill_checksum       VARCHAR(64) NOT NULL,
    effective_tool_codes JSONB       NOT NULL DEFAULT '[]'::JSONB,
    denied_tool_codes    JSONB       NOT NULL DEFAULT '[]'::JSONB,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_ai_agent_version_skill UNIQUE (agent_version_id, skill_id),
    CONSTRAINT uk_ai_agent_version_skill_version UNIQUE (agent_version_id, skill_version_id),
    CONSTRAINT ck_ai_agent_version_skill_effective_tools CHECK (jsonb_typeof(effective_tool_codes) = 'array'),
    CONSTRAINT ck_ai_agent_version_skill_denied_tools CHECK (jsonb_typeof(denied_tool_codes) = 'array')
);
CREATE INDEX IF NOT EXISTS idx_ai_agent_version_skill_skill
    ON lingxi_core.ai_agent_version_skill (skill_id, skill_version_id);

-- 运行事实允许同一Run内多次激活同一Skill，以保留多步骤Agent调用的真实轨迹。
CREATE TABLE IF NOT EXISTS lingxi_core.ai_execution_run_skill
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id               VARCHAR(64) NOT NULL,
    agent_version_id     BIGINT      NOT NULL,
    skill_id             BIGINT      NOT NULL,
    skill_version_id     BIGINT      NOT NULL,
    skill_code           VARCHAR(64) NOT NULL,
    skill_checksum       VARCHAR(64) NOT NULL,
    activation_reason    VARCHAR(32) NOT NULL,
    effective_tool_codes JSONB       NOT NULL DEFAULT '[]'::JSONB,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_execution_run_skill_tools CHECK (jsonb_typeof(effective_tool_codes) = 'array')
);
CREATE INDEX IF NOT EXISTS idx_execution_run_skill_run
    ON lingxi_core.ai_execution_run_skill (run_id, created_at);
CREATE INDEX IF NOT EXISTS idx_execution_run_skill_version
    ON lingxi_core.ai_execution_run_skill (skill_version_id, created_at DESC);

COMMIT;
