BEGIN;

-- 会话摘要快照只追加保存，全部关联字段均为带索引的逻辑外键。
CREATE TABLE IF NOT EXISTS lingxi_core.ai_conversation_summary_snapshot
(
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id          BIGINT      NOT NULL,
    user_id                  BIGINT      NOT NULL,
    application_version_id   BIGINT      NOT NULL,
    covered_user_sequence_no INTEGER     NOT NULL,
    summary                  TEXT        NOT NULL,
    prompt_version_id        BIGINT      NOT NULL,
    model_instance_id        BIGINT      NOT NULL,
    created_at               TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_conversation_summary_coverage UNIQUE (conversation_id, covered_user_sequence_no),
    CONSTRAINT ck_conversation_summary_sequence CHECK (covered_user_sequence_no > 0)
);

CREATE INDEX IF NOT EXISTS idx_conversation_summary_conversation
    ON lingxi_core.ai_conversation_summary_snapshot (conversation_id, covered_user_sequence_no DESC);
CREATE INDEX IF NOT EXISTS idx_conversation_summary_user
    ON lingxi_core.ai_conversation_summary_snapshot (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_conversation_summary_application_version
    ON lingxi_core.ai_conversation_summary_snapshot (application_version_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_conversation_summary_prompt
    ON lingxi_core.ai_conversation_summary_snapshot (prompt_version_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_conversation_summary_model
    ON lingxi_core.ai_conversation_summary_snapshot (model_instance_id, created_at DESC);

COMMENT ON TABLE lingxi_core.ai_conversation_summary_snapshot IS '会话滚动摘要不可变快照';
COMMENT ON COLUMN lingxi_core.ai_conversation_summary_snapshot.conversation_id IS '会话逻辑外键';
COMMENT ON COLUMN lingxi_core.ai_conversation_summary_snapshot.application_version_id IS '触发摘要的ApplicationVersion逻辑外键';
COMMENT ON COLUMN lingxi_core.ai_conversation_summary_snapshot.prompt_version_id IS '摘要PromptVersion逻辑外键';
COMMENT ON COLUMN lingxi_core.ai_conversation_summary_snapshot.model_instance_id IS '摘要模型实例逻辑外键';

COMMIT;
