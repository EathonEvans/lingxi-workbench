CREATE TABLE IF NOT EXISTS lingxi_core.ai_execution_task_snapshot
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id            VARCHAR(64)  NOT NULL,
    revision          INTEGER      NOT NULL,
    task_snapshot     JSONB        NOT NULL,
    snapshot_checksum VARCHAR(64)  NOT NULL,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_execution_task_revision UNIQUE (run_id, revision),
    CONSTRAINT ck_execution_task_revision CHECK (revision > 0),
    CONSTRAINT ck_execution_task_snapshot CHECK (jsonb_typeof(task_snapshot) = 'array')
);

CREATE INDEX IF NOT EXISTS idx_execution_task_run
    ON lingxi_core.ai_execution_task_snapshot (run_id, revision);

ALTER TABLE lingxi_core.ai_execution_step_attempt
    RENAME COLUMN plan_no TO task_revision;

ALTER TABLE lingxi_core.ai_execution_step_attempt
    DROP CONSTRAINT IF EXISTS ck_execution_step_numbers;

ALTER TABLE lingxi_core.ai_execution_step_attempt
    ADD CONSTRAINT ck_execution_step_numbers CHECK (task_revision > 0 AND attempt_no > 0);

ALTER TABLE lingxi_core.ai_execution_run
    RENAME COLUMN planner_model_instance_id TO supervisor_model_instance_id;

ALTER TABLE lingxi_core.ai_execution_run
    RENAME COLUMN planner_prompt_version_id TO supervisor_prompt_version_id;

DROP INDEX IF EXISTS lingxi_core.idx_execution_run_planner_model;
DROP INDEX IF EXISTS lingxi_core.idx_execution_run_planner_prompt;
CREATE INDEX IF NOT EXISTS idx_execution_run_supervisor_model
    ON lingxi_core.ai_execution_run (supervisor_model_instance_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_execution_run_supervisor_prompt
    ON lingxi_core.ai_execution_run (supervisor_prompt_version_id, created_at DESC);
