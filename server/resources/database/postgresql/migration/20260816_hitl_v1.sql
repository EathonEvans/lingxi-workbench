-- Human-in-the-Loop：Tool 精确审批、可恢复检查点与同一 Run 状态机。
-- 全部关联均为逻辑外键，由 Service 事务校验归属和生命周期。

ALTER TABLE lingxi_core.ai_tool
    ADD COLUMN IF NOT EXISTS risk_level VARCHAR(16) NOT NULL DEFAULT 'LOW',
    ADD COLUMN IF NOT EXISTS approval_required BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS approval_ttl_seconds INTEGER NOT NULL DEFAULT 1800,
    ADD COLUMN IF NOT EXISTS resource_scope VARCHAR(255) NOT NULL DEFAULT '当前会话授权范围';

ALTER TABLE lingxi_core.ai_execution_run
    ALTER COLUMN planner_model_instance_id DROP NOT NULL,
    ALTER COLUMN planner_prompt_version_id DROP NOT NULL,
    ADD COLUMN IF NOT EXISTS capability_code VARCHAR(64),
    ADD COLUMN IF NOT EXISTS execution_mode VARCHAR(32),
    ADD COLUMN IF NOT EXISTS status VARCHAR(32) NOT NULL DEFAULT 'RUNNING',
    ADD COLUMN IF NOT EXISTS current_stage VARCHAR(64) NOT NULL DEFAULT 'EXECUTION',
    ADD COLUMN IF NOT EXISTS revision INTEGER NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ADD COLUMN IF NOT EXISTS completed_at TIMESTAMPTZ;

ALTER TABLE lingxi_core.ai_interaction_session
    ADD COLUMN IF NOT EXISTS assistant_message_id BIGINT,
    ADD COLUMN IF NOT EXISTS checkpoint_id BIGINT,
    ADD COLUMN IF NOT EXISTS revision INTEGER NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS approval_fingerprint VARCHAR(64),
    ADD COLUMN IF NOT EXISTS decision VARCHAR(16),
    ADD COLUMN IF NOT EXISTS decided_by BIGINT,
    ADD COLUMN IF NOT EXISTS decided_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS idempotency_key VARCHAR(128);

CREATE UNIQUE INDEX IF NOT EXISTS uk_interaction_session_idempotency
    ON lingxi_core.ai_interaction_session (idempotency_key)
    WHERE idempotency_key IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_interaction_session_assistant
    ON lingxi_core.ai_interaction_session (assistant_message_id, status);

CREATE TABLE IF NOT EXISTS lingxi_core.ai_execution_checkpoint
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id             VARCHAR(64) NOT NULL,
    assistant_message_id BIGINT NOT NULL,
    checkpoint_type    VARCHAR(32) NOT NULL,
    status             VARCHAR(16) NOT NULL,
    checkpoint_version INTEGER NOT NULL DEFAULT 1,
    payload             JSONB NOT NULL,
    checksum            VARCHAR(64) NOT NULL,
    expires_at          TIMESTAMPTZ NOT NULL,
    consumed_at         TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_execution_checkpoint_version CHECK (checkpoint_version > 0)
);
CREATE INDEX IF NOT EXISTS idx_execution_checkpoint_run
    ON lingxi_core.ai_execution_checkpoint (run_id, status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_execution_checkpoint_expiry
    ON lingxi_core.ai_execution_checkpoint (status, expires_at);

CREATE TABLE IF NOT EXISTS lingxi_core.ai_capability_invocation
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id               VARCHAR(64) NOT NULL,
    checkpoint_id        BIGINT NOT NULL,
    interaction_id       BIGINT,
    assistant_message_id BIGINT NOT NULL,
    tool_code            VARCHAR(64) NOT NULL,
    tool_input           JSONB NOT NULL,
    resource_scope       VARCHAR(255) NOT NULL,
    approval_fingerprint VARCHAR(64) NOT NULL,
    status               VARCHAR(32) NOT NULL,
    idempotency_key      VARCHAR(128),
    result_digest        VARCHAR(64),
    error_code           VARCHAR(64),
    started_at           TIMESTAMPTZ,
    finished_at          TIMESTAMPTZ,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_capability_invocation_interaction
    ON lingxi_core.ai_capability_invocation (interaction_id)
    WHERE interaction_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_capability_invocation_run
    ON lingxi_core.ai_capability_invocation (run_id, status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_capability_invocation_checkpoint
    ON lingxi_core.ai_capability_invocation (checkpoint_id);
