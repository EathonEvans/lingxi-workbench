BEGIN;

-- Skill稳定主体只保存治理元数据；可变内容进入草稿，运行时只能读取不可变发布版本。
CREATE TABLE IF NOT EXISTS lingxi_core.ai_skill
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                 VARCHAR(64)  NOT NULL,
    code                 VARCHAR(64)  NOT NULL,
    description          VARCHAR(500),
    source_type          VARCHAR(32)  NOT NULL,
    visibility           VARCHAR(16)  NOT NULL,
    owner_user_id        BIGINT,
    status               VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    security_status      VARCHAR(16)  NOT NULL DEFAULT 'NORMAL',
    published_version_id BIGINT,
    created_by           BIGINT       NOT NULL,
    updated_by           BIGINT       NOT NULL,
    created_at           TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_ai_skill_code UNIQUE (code),
    CONSTRAINT ck_ai_skill_code CHECK (code = LOWER(BTRIM(code))),
    CONSTRAINT ck_ai_skill_source CHECK (
        source_type IN ('SYSTEM_PRESET', 'USER_CREATED', 'THIRD_PARTY_IMPORTED')
    ),
    CONSTRAINT ck_ai_skill_visibility CHECK (visibility IN ('PRIVATE', 'PROJECT', 'SYSTEM')),
    CONSTRAINT ck_ai_skill_owner CHECK (
        (source_type = 'SYSTEM_PRESET' AND owner_user_id IS NULL)
        OR (source_type <> 'SYSTEM_PRESET' AND owner_user_id IS NOT NULL)
    ),
    CONSTRAINT ck_ai_skill_system_visibility CHECK (
        source_type <> 'SYSTEM_PRESET' OR visibility = 'SYSTEM'
    ),
    CONSTRAINT ck_ai_skill_status CHECK (status IN ('ACTIVE', 'DISABLED')),
    CONSTRAINT ck_ai_skill_security CHECK (security_status IN ('NORMAL', 'QUARANTINED', 'REVOKED'))
);
CREATE INDEX IF NOT EXISTS idx_ai_skill_scope
    ON lingxi_core.ai_skill (visibility, owner_user_id, status, updated_at DESC);
CREATE INDEX IF NOT EXISTS idx_ai_skill_published_version
    ON lingxi_core.ai_skill (published_version_id) WHERE published_version_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS lingxi_core.ai_skill_draft
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_id             BIGINT       NOT NULL,
    base_version_id      BIGINT,
    schema_version       INTEGER      NOT NULL DEFAULT 1,
    instructions         TEXT         NOT NULL DEFAULT '',
    activation_mode      VARCHAR(32)  NOT NULL DEFAULT 'EXPLICIT_ONLY',
    requested_tool_codes JSONB        NOT NULL DEFAULT '[]'::JSONB,
    revision             BIGINT       NOT NULL DEFAULT 0,
    change_note          VARCHAR(255),
    created_by           BIGINT       NOT NULL,
    updated_by           BIGINT       NOT NULL,
    created_at           TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_ai_skill_draft_skill UNIQUE (skill_id),
    CONSTRAINT ck_ai_skill_draft_schema CHECK (schema_version = 1),
    CONSTRAINT ck_ai_skill_draft_activation CHECK (activation_mode IN ('EXPLICIT_ONLY', 'MODEL_ROUTED')),
    CONSTRAINT ck_ai_skill_draft_tools CHECK (jsonb_typeof(requested_tool_codes) = 'array'),
    CONSTRAINT ck_ai_skill_draft_revision CHECK (revision >= 0)
);
CREATE INDEX IF NOT EXISTS idx_ai_skill_draft_base_version
    ON lingxi_core.ai_skill_draft (base_version_id) WHERE base_version_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS lingxi_core.ai_skill_version
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_id          BIGINT       NOT NULL,
    version_no        INTEGER      NOT NULL,
    version_name      VARCHAR(64)  NOT NULL,
    schema_version    INTEGER      NOT NULL,
    snapshot          JSONB        NOT NULL,
    snapshot_checksum VARCHAR(64)  NOT NULL,
    scan_report       JSONB        NOT NULL,
    change_note       VARCHAR(255),
    published_by      BIGINT       NOT NULL,
    published_at      TIMESTAMPTZ  NOT NULL,
    revoked_by        BIGINT,
    revoked_at        TIMESTAMPTZ,
    revoke_reason     VARCHAR(500),
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_ai_skill_version_no UNIQUE (skill_id, version_no),
    CONSTRAINT uk_ai_skill_version_snapshot UNIQUE (skill_id, snapshot_checksum),
    CONSTRAINT ck_ai_skill_version_no CHECK (version_no > 0),
    CONSTRAINT ck_ai_skill_version_schema CHECK (schema_version = 1),
    CONSTRAINT ck_ai_skill_version_snapshot CHECK (jsonb_typeof(snapshot) = 'object'),
    CONSTRAINT ck_ai_skill_version_scan CHECK (jsonb_typeof(scan_report) = 'object'),
    CONSTRAINT ck_ai_skill_version_revoke CHECK (
        (revoked_at IS NULL AND revoked_by IS NULL AND revoke_reason IS NULL)
        OR (revoked_at IS NOT NULL AND revoked_by IS NOT NULL AND BTRIM(revoke_reason) <> '')
    )
);
CREATE INDEX IF NOT EXISTS idx_ai_skill_version_skill
    ON lingxi_core.ai_skill_version (skill_id, version_no DESC);
CREATE INDEX IF NOT EXISTS idx_ai_skill_version_active
    ON lingxi_core.ai_skill_version (skill_id, id) WHERE revoked_at IS NULL;

INSERT INTO lingxi_core.sys_menu
    (parent_id, name, code, menu_type, route_path, component, icon, permission_code,
     sort_order, visible, status)
SELECT parent.id, 'Skill管理', 'SKILL_LIST', 'MENU', '/agent/skill',
       'skill/index', 'ri:book-marked-line', 'skill:list', 20, TRUE, 'ACTIVE'
FROM lingxi_core.sys_menu parent
WHERE parent.code = 'AGENT'
ON CONFLICT (code) DO UPDATE
SET parent_id = EXCLUDED.parent_id,
    name = EXCLUDED.name,
    route_path = EXCLUDED.route_path,
    component = EXCLUDED.component,
    icon = EXCLUDED.icon,
    permission_code = EXCLUDED.permission_code,
    sort_order = EXCLUDED.sort_order,
    visible = TRUE,
    status = 'ACTIVE';

INSERT INTO lingxi_core.sys_menu
    (parent_id, name, code, menu_type, permission_code, sort_order, visible, status)
SELECT parent.id, action.name, action.code, 'BUTTON', action.permission_code,
       action.sort_order, FALSE, 'ACTIVE'
FROM (VALUES
    ('Skill维护', 'SKILL_MANAGE', 'skill:manage', 10),
    ('Skill发布', 'SKILL_PUBLISH', 'skill:publish', 20),
    ('Skill撤销', 'SKILL_REVOKE', 'skill:revoke', 30)
) AS action(name, code, permission_code, sort_order)
JOIN lingxi_core.sys_menu parent ON parent.code = 'SKILL_LIST'
ON CONFLICT (code) DO UPDATE
SET parent_id = EXCLUDED.parent_id,
    name = EXCLUDED.name,
    permission_code = EXCLUDED.permission_code,
    sort_order = EXCLUDED.sort_order,
    visible = FALSE,
    status = 'ACTIVE';

COMMIT;
