BEGIN;

-- ===== 站内通知中心 =====
-- 承载主动触达消息：HITL 待确认（P1）、定时任务结果（P3）等。
-- 全部关联均为逻辑外键，由 Service 事务校验归属与状态。

CREATE TABLE IF NOT EXISTS lingxi_core.ai_notification (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL,
    type        VARCHAR(32) NOT NULL,
    title       VARCHAR(128) NOT NULL,
    content     VARCHAR(512),
    payload     JSONB,
    dedup_key   VARCHAR(128),
    read_at     TIMESTAMPTZ,
    deleted_at  TIMESTAMPTZ,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON COLUMN lingxi_core.ai_notification.dedup_key IS '幂等去重键，如 hitl:{interactionId}；为空的记录不去重';

CREATE UNIQUE INDEX IF NOT EXISTS uk_ai_notification_dedup
    ON lingxi_core.ai_notification (user_id, dedup_key)
    WHERE dedup_key IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_ai_notification_user_created
    ON lingxi_core.ai_notification (user_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_ai_notification_unread
    ON lingxi_core.ai_notification (user_id)
    WHERE read_at IS NULL AND deleted_at IS NULL;

COMMIT;
