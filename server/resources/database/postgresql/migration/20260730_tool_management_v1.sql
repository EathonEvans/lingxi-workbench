BEGIN;

-- Tool 主表只保存控制面定义。Java 执行器仍由运行端按 code 注册，
-- 因此数据库与业务模块之间不存在物理外键或代码依赖。
CREATE TABLE IF NOT EXISTS lingxi_core.ai_tool
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(64)  NOT NULL,
    code             VARCHAR(64)  NOT NULL,
    description      VARCHAR(1000) NOT NULL,
    source_type      VARCHAR(32)  NOT NULL DEFAULT 'LOCAL_FUNCTION',
    parameter_schema JSONB        NOT NULL DEFAULT '{"type":"object","properties":{}}'::JSONB,
    status           VARCHAR(16)  NOT NULL DEFAULT 'DISABLED',
    created_by       BIGINT       NOT NULL,
    updated_by       BIGINT       NOT NULL,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_ai_tool_code UNIQUE (code),
    CONSTRAINT ck_ai_tool_code CHECK (code = LOWER(BTRIM(code))),
    CONSTRAINT ck_ai_tool_source_type CHECK (source_type IN ('LOCAL_FUNCTION')),
    CONSTRAINT ck_ai_tool_parameter_schema CHECK (jsonb_typeof(parameter_schema) = 'object'),
    CONSTRAINT ck_ai_tool_status CHECK (status IN ('ACTIVE', 'DISABLED'))
);

COMMENT ON TABLE lingxi_core.ai_tool
    IS 'Tool稳定定义；执行器由运行端按code注册，表内不保存可执行代码';
COMMENT ON COLUMN lingxi_core.ai_tool.code
    IS '跨Agent配置与运行时执行器使用的稳定工具编码';
COMMENT ON COLUMN lingxi_core.ai_tool.source_type
    IS '工具来源；第一阶段仅支持LOCAL_FUNCTION';
COMMENT ON COLUMN lingxi_core.ai_tool.parameter_schema
    IS '符合OpenAI Function Calling规范的JSON Schema参数定义';

