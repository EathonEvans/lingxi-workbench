BEGIN;

-- 领域仅用于控制面筛选与发布校验，运行时继续执行Application冻结的能力快照。
CREATE TABLE IF NOT EXISTS lingxi_core.ai_domain
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id   BIGINT,
    root_id     BIGINT,
    name        VARCHAR(64)  NOT NULL,
    code        VARCHAR(64)  NOT NULL,
    description VARCHAR(500),
    depth       INTEGER      NOT NULL,
    sort_order  INTEGER      NOT NULL DEFAULT 0,
    status      VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    created_by  BIGINT       NOT NULL,
    updated_by  BIGINT       NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_ai_domain_code UNIQUE (code),
    CONSTRAINT ck_ai_domain_code CHECK (code = LOWER(BTRIM(code))),
    CONSTRAINT ck_ai_domain_depth CHECK (depth BETWEEN 1 AND 3),
    CONSTRAINT ck_ai_domain_status CHECK (status IN ('ACTIVE', 'DISABLED'))
);
CREATE INDEX IF NOT EXISTS idx_ai_domain_parent ON lingxi_core.ai_domain (parent_id, sort_order, id);
CREATE INDEX IF NOT EXISTS idx_ai_domain_root ON lingxi_core.ai_domain (root_id, depth, status);

-- Agent角色只保留主Agent和领域专家；Plan & Execute由主Agent能力承载。
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'lingxi_core' AND table_name = 'ai_agent' AND column_name = 'agent_type'
    ) THEN
        ALTER TABLE lingxi_core.ai_agent RENAME COLUMN agent_type TO role;
    END IF;
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'lingxi_core' AND table_name = 'ai_agent_draft' AND column_name = 'plan_executor_policy'
    ) THEN
        ALTER TABLE lingxi_core.ai_agent_draft RENAME COLUMN plan_executor_policy TO plan_policy;
    END IF;
END
$$;

ALTER TABLE lingxi_core.ai_agent
    ADD COLUMN IF NOT EXISTS domain_id BIGINT;
UPDATE lingxi_core.ai_agent SET role = 'SPECIALIST' WHERE role = 'REACT';
UPDATE lingxi_core.ai_agent SET role = 'SUPERVISOR' WHERE role = 'PLAN_EXECUTOR';
ALTER TABLE lingxi_core.ai_agent ALTER COLUMN role SET DEFAULT 'SPECIALIST';
ALTER TABLE lingxi_core.ai_agent
    DROP CONSTRAINT IF EXISTS ck_ai_agent_type,
    DROP CONSTRAINT IF EXISTS ck_ai_agent_role;
ALTER TABLE lingxi_core.ai_agent
    ADD CONSTRAINT ck_ai_agent_role CHECK (role IN ('SPECIALIST', 'SUPERVISOR'));
CREATE INDEX IF NOT EXISTS idx_ai_agent_domain ON lingxi_core.ai_agent (domain_id, role, status);

ALTER TABLE lingxi_core.ai_agent_draft
    ALTER COLUMN schema_version SET DEFAULT 7,
    DROP CONSTRAINT IF EXISTS ck_ai_agent_draft_schema_version,
    DROP CONSTRAINT IF EXISTS ck_ai_agent_draft_plan_executor_policy;
UPDATE lingxi_core.ai_agent_draft SET schema_version = 7;
ALTER TABLE lingxi_core.ai_agent_draft
    ADD CONSTRAINT ck_ai_agent_draft_schema_version CHECK (schema_version = 7),
    ADD CONSTRAINT ck_ai_agent_draft_plan_policy CHECK (
        plan_policy IS NULL OR jsonb_typeof(plan_policy) = 'object'
    );
ALTER TABLE lingxi_core.ai_agent_version
    DROP CONSTRAINT IF EXISTS ck_ai_agent_version_schema;
ALTER TABLE lingxi_core.ai_agent_version
    ADD CONSTRAINT ck_ai_agent_version_schema CHECK (schema_version > 0);

ALTER TABLE lingxi_core.ai_intent_tree ADD COLUMN IF NOT EXISTS domain_id BIGINT;
CREATE INDEX IF NOT EXISTS idx_ai_intent_tree_domain
    ON lingxi_core.ai_intent_tree (domain_id, status, updated_at DESC);

ALTER TABLE lingxi_core.ai_application ADD COLUMN IF NOT EXISTS domain_id BIGINT;
CREATE INDEX IF NOT EXISTS idx_ai_application_domain
    ON lingxi_core.ai_application (domain_id, status, updated_at DESC);

ALTER TABLE lingxi_core.ai_application_draft
    ALTER COLUMN schema_version SET DEFAULT 10,
    DROP CONSTRAINT IF EXISTS ck_ai_application_draft_schema;
UPDATE lingxi_core.ai_application_draft
SET schema_version = 10,
    definition = jsonb_set(definition, '{schemaVersion}', '10'::jsonb, TRUE);
ALTER TABLE lingxi_core.ai_application_draft
    ADD CONSTRAINT ck_ai_application_draft_schema CHECK (schema_version = 10);
ALTER TABLE lingxi_core.ai_application_version
    DROP CONSTRAINT IF EXISTS ck_ai_application_version_schema;
ALTER TABLE lingxi_core.ai_application_version
    ADD CONSTRAINT ck_ai_application_version_schema CHECK (schema_version > 0);

INSERT INTO lingxi_core.sys_menu
    (parent_id, name, code, menu_type, route_path, component, icon, permission_code, sort_order, visible, status)
SELECT parent.id, '领域管理', 'DOMAIN_LIST', 'MENU', '/application/domain',
       'domain/index', 'ri:git-branch-line', 'domain:list', 5, TRUE, 'ACTIVE'
FROM lingxi_core.sys_menu parent
WHERE parent.code = 'APPLICATION'
ON CONFLICT (code) DO UPDATE
SET parent_id = EXCLUDED.parent_id,
    name = EXCLUDED.name,
    route_path = EXCLUDED.route_path,
    component = EXCLUDED.component,
    icon = EXCLUDED.icon,
    permission_code = EXCLUDED.permission_code,
    sort_order = EXCLUDED.sort_order,
    visible = TRUE,
    status = 'ACTIVE';

INSERT INTO lingxi_core.sys_menu
    (parent_id, name, code, menu_type, permission_code, sort_order, visible, status)
SELECT parent.id, action.name, action.code, 'BUTTON', action.permission_code,
       action.sort_order, FALSE, 'ACTIVE'
FROM (VALUES
    ('新增领域', 'DOMAIN_CREATE', 'domain:create', 10),
    ('修改领域', 'DOMAIN_UPDATE', 'domain:update', 20),
    ('删除领域', 'DOMAIN_DELETE', 'domain:delete', 30)
) AS action(name, code, permission_code, sort_order)
JOIN lingxi_core.sys_menu parent ON parent.code = 'DOMAIN_LIST'
ON CONFLICT (code) DO UPDATE
SET parent_id = EXCLUDED.parent_id,
    name = EXCLUDED.name,
    permission_code = EXCLUDED.permission_code,
    sort_order = EXCLUDED.sort_order,
    visible = FALSE,
    status = 'ACTIVE';

COMMIT;
