BEGIN;

-- 关联字段统一使用逻辑外键，由服务层校验归属与状态，数据库仅建立查询索引。
CREATE TABLE IF NOT EXISTS lingxi_core.ai_intent_tree
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                 VARCHAR(64)  NOT NULL,
    code                 VARCHAR(64)  NOT NULL,
    description          VARCHAR(500),
    status               VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    published_version_id BIGINT,
    created_by           BIGINT       NOT NULL,
    updated_by           BIGINT       NOT NULL,
    created_at           TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_ai_intent_tree_code UNIQUE (code),
    CONSTRAINT ck_ai_intent_tree_code CHECK (code = LOWER(BTRIM(code)))
);

CREATE TABLE IF NOT EXISTS lingxi_core.ai_intent_tree_draft
(
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    intent_tree_id              BIGINT       NOT NULL,
    base_version_id             BIGINT,
    schema_version              INTEGER      NOT NULL DEFAULT 1,
    embedding_model_instance_id BIGINT,
    definition                  JSONB        NOT NULL,
    revision                    BIGINT       NOT NULL DEFAULT 0,
    change_note                 VARCHAR(255),
    created_by                  BIGINT       NOT NULL,
    updated_by                  BIGINT       NOT NULL,
    created_at                  TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at                  TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_ai_intent_tree_draft_tree UNIQUE (intent_tree_id),
    CONSTRAINT ck_ai_intent_tree_draft_schema CHECK (schema_version > 0),
    CONSTRAINT ck_ai_intent_tree_draft_revision CHECK (revision >= 0)
);

CREATE TABLE IF NOT EXISTS lingxi_core.ai_intent_tree_version
(
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    intent_tree_id              BIGINT       NOT NULL,
    version_no                  INTEGER      NOT NULL,
    version_name                VARCHAR(64)  NOT NULL,
    schema_version              INTEGER      NOT NULL,
    embedding_model_instance_id BIGINT       NOT NULL,
    definition_snapshot         JSONB        NOT NULL,
    snapshot_checksum           VARCHAR(64)  NOT NULL,
    change_note                 VARCHAR(255),
    published_by                BIGINT       NOT NULL,
    published_at                TIMESTAMPTZ  NOT NULL,
    created_at                  TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_ai_intent_tree_version_no UNIQUE (intent_tree_id, version_no),
    CONSTRAINT uk_ai_intent_tree_version_snapshot UNIQUE (intent_tree_id, snapshot_checksum),
    CONSTRAINT ck_ai_intent_tree_version_no CHECK (version_no > 0),
    CONSTRAINT ck_ai_intent_tree_version_schema CHECK (schema_version > 0)
);

CREATE INDEX IF NOT EXISTS idx_ai_intent_tree_version_tree
    ON lingxi_core.ai_intent_tree_version (intent_tree_id, version_no DESC);
CREATE INDEX IF NOT EXISTS idx_ai_intent_tree_status
    ON lingxi_core.ai_intent_tree (status, updated_at DESC);
CREATE INDEX IF NOT EXISTS idx_ai_intent_tree_published_version
    ON lingxi_core.ai_intent_tree (published_version_id);
CREATE INDEX IF NOT EXISTS idx_ai_intent_tree_draft_base_version
    ON lingxi_core.ai_intent_tree_draft (base_version_id);
CREATE INDEX IF NOT EXISTS idx_ai_intent_tree_draft_embedding_model
    ON lingxi_core.ai_intent_tree_draft (embedding_model_instance_id);
CREATE INDEX IF NOT EXISTS idx_ai_intent_tree_version_embedding_model
    ON lingxi_core.ai_intent_tree_version (embedding_model_instance_id);

-- 意图向量属于发布版本的不可变派生事实；关联字段均为带索引的逻辑外键。
CREATE TABLE IF NOT EXISTS lingxi_vector.intent_tree_vector
(
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    intent_tree_id              BIGINT       NOT NULL,
    intent_tree_version_id      BIGINT       NOT NULL,
    intent_node_id              VARCHAR(64)  NOT NULL,
    intent_code                 VARCHAR(64)  NOT NULL,
    vector_kind                 VARCHAR(16)  NOT NULL,
    source_ordinal              INTEGER      NOT NULL,
    source_hash                 VARCHAR(64)  NOT NULL,
    embedding_model_instance_id BIGINT       NOT NULL,
    embedding_dimension         INTEGER      NOT NULL,
    embedding                   VECTOR       NOT NULL,
    created_at                  TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_intent_tree_vector_source UNIQUE
        (intent_tree_version_id, intent_node_id, vector_kind, source_ordinal),
    CONSTRAINT ck_intent_tree_vector_kind CHECK (vector_kind IN ('PROTOTYPE', 'EXAMPLE')),
    CONSTRAINT ck_intent_tree_vector_ordinal CHECK (source_ordinal >= 0),
    CONSTRAINT ck_intent_tree_vector_dimension CHECK (embedding_dimension > 0)
);
CREATE INDEX IF NOT EXISTS idx_intent_tree_vector_version
    ON lingxi_vector.intent_tree_vector
        (intent_tree_version_id, embedding_model_instance_id, embedding_dimension, intent_code);

-- 澄清会话锁定 ApplicationVersion 与 IntentTreeVersion，跨消息恢复时不跟随新发布版本漂移。
CREATE TABLE IF NOT EXISTS lingxi_core.ai_intent_routing_session
(
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id        BIGINT       NOT NULL,
    user_id                BIGINT       NOT NULL,
    application_version_id BIGINT       NOT NULL,
    intent_tree_version_id BIGINT       NOT NULL,
    status                 VARCHAR(16)  NOT NULL,
    clarification_type     VARCHAR(32)  NOT NULL,
    round_no               INTEGER      NOT NULL DEFAULT 1,
    context                JSONB        NOT NULL,
    expires_at             TIMESTAMPTZ  NOT NULL,
    created_at             TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at             TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_intent_routing_session_round CHECK (round_no BETWEEN 1 AND 2),
    CONSTRAINT ck_intent_routing_session_status
        CHECK (status IN ('PENDING', 'RESOLVED', 'CANCELLED', 'EXPIRED', 'COMPLETED', 'FAILED')),
    CONSTRAINT ck_intent_routing_session_type
        CHECK (clarification_type IN ('INTENT_DISAMBIGUATION', 'MISSING_SLOT'))
);
CREATE INDEX IF NOT EXISTS idx_intent_routing_session_pending
    ON lingxi_core.ai_intent_routing_session
        (conversation_id, user_id, application_version_id, status, expires_at DESC);
CREATE INDEX IF NOT EXISTS idx_intent_routing_session_intent_version
    ON lingxi_core.ai_intent_routing_session (intent_tree_version_id);

INSERT INTO lingxi_core.sys_menu
    (parent_id, name, code, menu_type, route_path, component, icon, permission_code, sort_order, visible, status)
SELECT parent.id, '意图树管理', 'INTENT_TREE_LIST', 'MENU', '/application/intent-tree',
       'intent-tree/index', 'ri:node-tree', 'intent-tree:list', 20, TRUE, 'ACTIVE'
FROM lingxi_core.sys_menu parent
WHERE parent.code = 'APPLICATION'
ON CONFLICT (code) DO UPDATE
SET parent_id = EXCLUDED.parent_id,
    name = EXCLUDED.name,
    route_path = EXCLUDED.route_path,
    component = EXCLUDED.component,
    icon = EXCLUDED.icon,
    permission_code = EXCLUDED.permission_code,
    sort_order = EXCLUDED.sort_order,
    visible = TRUE,
    status = 'ACTIVE';

INSERT INTO lingxi_core.sys_menu
    (parent_id, name, code, menu_type, permission_code, sort_order, visible, status)
SELECT parent.id, action.name, action.code, 'BUTTON', action.permission_code,
       action.sort_order, FALSE, 'ACTIVE'
FROM (VALUES
    ('意图树维护', 'INTENT_TREE_MANAGE', 'intent-tree:manage', 10),
    ('意图树发布', 'INTENT_TREE_PUBLISH', 'intent-tree:publish', 20)
) AS action(name, code, permission_code, sort_order)
JOIN lingxi_core.sys_menu parent ON parent.code = 'INTENT_TREE_LIST'
ON CONFLICT (code) DO UPDATE
SET parent_id = EXCLUDED.parent_id,
    name = EXCLUDED.name,
    permission_code = EXCLUDED.permission_code,
    sort_order = EXCLUDED.sort_order,
    visible = FALSE,
    status = 'ACTIVE';

COMMIT;
