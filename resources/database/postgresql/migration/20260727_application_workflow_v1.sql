BEGIN;

CREATE TABLE IF NOT EXISTS lingxi_core.ai_application
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                 VARCHAR(64)  NOT NULL,
    code                 VARCHAR(64)  NOT NULL,
    description          VARCHAR(500),
    status               VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    published_version_id BIGINT,
    created_by           BIGINT       NOT NULL,
    updated_by           BIGINT       NOT NULL,
    created_at           TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_ai_application_code UNIQUE (code),
    CONSTRAINT ck_ai_application_code CHECK (code = LOWER(BTRIM(code))),
    CONSTRAINT ck_ai_application_status CHECK (status IN ('ACTIVE', 'DISABLED'))
);

CREATE TABLE IF NOT EXISTS lingxi_core.ai_application_draft
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id   BIGINT       NOT NULL,
    base_version_id  BIGINT,
    schema_version   INTEGER      NOT NULL DEFAULT 1,
    definition       JSONB        NOT NULL,
    revision         BIGINT       NOT NULL DEFAULT 0,
    change_note      VARCHAR(255),
    created_by       BIGINT       NOT NULL,
    updated_by       BIGINT       NOT NULL,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_ai_application_draft_application UNIQUE (application_id),
    CONSTRAINT ck_ai_application_draft_schema CHECK (schema_version > 0),
    CONSTRAINT ck_ai_application_draft_revision CHECK (revision >= 0)
);

CREATE TABLE IF NOT EXISTS lingxi_core.ai_application_version
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id      BIGINT       NOT NULL,
    version_no          INTEGER      NOT NULL,
    version_name        VARCHAR(64)  NOT NULL,
    schema_version      INTEGER      NOT NULL,
    definition_snapshot JSONB        NOT NULL,
    snapshot_checksum   VARCHAR(64)  NOT NULL,
    change_note         VARCHAR(255),
    published_by        BIGINT       NOT NULL,
    published_at        TIMESTAMPTZ  NOT NULL,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_ai_application_version_no UNIQUE (application_id, version_no),
    CONSTRAINT uk_ai_application_version_snapshot
        UNIQUE (application_id, snapshot_checksum),
    CONSTRAINT ck_ai_application_version_no CHECK (version_no > 0),
    CONSTRAINT ck_ai_application_version_schema CHECK (schema_version > 0)
);

CREATE INDEX IF NOT EXISTS idx_ai_application_version_application
    ON lingxi_core.ai_application_version (application_id, version_no DESC);
CREATE INDEX IF NOT EXISTS idx_ai_application_published_version
    ON lingxi_core.ai_application (published_version_id)
    WHERE published_version_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_ai_application_draft_base_version
    ON lingxi_core.ai_application_draft (base_version_id)
    WHERE base_version_id IS NOT NULL;

COMMIT;
