-- Plan-and-Execute运行数据只追加保存；全部关联字段均为带索引的逻辑外键。
CREATE TABLE IF NOT EXISTS lingxi_core.ai_execution_run
(
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id                    VARCHAR(64) NOT NULL,
    assistant_message_id      BIGINT      NOT NULL,
    conversation_id           BIGINT      NOT NULL,
    user_id                   BIGINT      NOT NULL,
    application_id            BIGINT      NOT NULL,
    application_version_id    BIGINT      NOT NULL,
    planner_model_instance_id BIGINT      NOT NULL,
    planner_prompt_version_id BIGINT      NOT NULL,
    created_at                TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_execution_run_id UNIQUE (run_id),
    CONSTRAINT uk_execution_run_message UNIQUE (assistant_message_id)
);
CREATE INDEX IF NOT EXISTS idx_execution_run_conversation
    ON lingxi_core.ai_execution_run (conversation_id, user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_execution_run_application_version
    ON lingxi_core.ai_execution_run (application_version_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_execution_run_application
    ON lingxi_core.ai_execution_run (application_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_execution_run_planner_model
    ON lingxi_core.ai_execution_run (planner_model_instance_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_execution_run_planner_prompt
    ON lingxi_core.ai_execution_run (planner_prompt_version_id, created_at DESC);

CREATE TABLE IF NOT EXISTS lingxi_core.ai_execution_plan_snapshot
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id            VARCHAR(64)  NOT NULL,
    plan_no           INTEGER      NOT NULL,
    decision_action   VARCHAR(32)  NOT NULL,
    capability_code   VARCHAR(64),
    decision_snapshot JSONB        NOT NULL,
    snapshot_checksum VARCHAR(64)  NOT NULL,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_execution_plan_no UNIQUE (run_id, plan_no),
    CONSTRAINT ck_execution_plan_no CHECK (plan_no > 0)
);
CREATE INDEX IF NOT EXISTS idx_execution_plan_run
    ON lingxi_core.ai_execution_plan_snapshot (run_id, plan_no);

CREATE TABLE IF NOT EXISTS lingxi_core.ai_execution_step_attempt
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id           VARCHAR(64)  NOT NULL,
    plan_no          INTEGER      NOT NULL,
    step_id          VARCHAR(32)  NOT NULL,
    attempt_no       INTEGER      NOT NULL,
    capability_code  VARCHAR(64)  NOT NULL,
    status           VARCHAR(16)  NOT NULL,
    step_snapshot    JSONB        NOT NULL,
    result_content   TEXT,
    error_code       VARCHAR(64),
    started_at       TIMESTAMPTZ  NOT NULL,
    finished_at      TIMESTAMPTZ,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_execution_step_attempt UNIQUE (run_id, plan_no, step_id, attempt_no),
    CONSTRAINT ck_execution_step_numbers CHECK (plan_no > 0 AND attempt_no > 0)
);
CREATE INDEX IF NOT EXISTS idx_execution_step_run
    ON lingxi_core.ai_execution_step_attempt (run_id, plan_no, step_id, attempt_no);
CREATE INDEX IF NOT EXISTS idx_execution_step_status
    ON lingxi_core.ai_execution_step_attempt (run_id, status, started_at);

CREATE TABLE IF NOT EXISTS lingxi_core.ai_execution_event
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id       VARCHAR(64)  NOT NULL,
    sequence_no  BIGINT       NOT NULL,
    event_type   VARCHAR(32)  NOT NULL,
    plan_no      INTEGER,
    step_id      VARCHAR(32),
    display_name VARCHAR(128),
    step_status  VARCHAR(16),
    message      VARCHAR(500),
    occurred_at  TIMESTAMPTZ  NOT NULL,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_execution_event_sequence UNIQUE (run_id, sequence_no),
    CONSTRAINT ck_execution_event_sequence CHECK (sequence_no > 0)
);
CREATE INDEX IF NOT EXISTS idx_execution_event_run
    ON lingxi_core.ai_execution_event (run_id, sequence_no);

CREATE TABLE IF NOT EXISTS lingxi_core.ai_interaction_session
(
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id        BIGINT       NOT NULL,
    user_id                BIGINT       NOT NULL,
    application_version_id BIGINT       NOT NULL,
    run_id                 VARCHAR(64),
    interaction_type       VARCHAR(32)  NOT NULL,
    status                 VARCHAR(16)  NOT NULL,
    round_no               INTEGER      NOT NULL DEFAULT 1,
    context                JSONB        NOT NULL,
    expires_at             TIMESTAMPTZ  NOT NULL,
    created_at             TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at             TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_interaction_session_round CHECK (round_no > 0)
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_interaction_session_pending
    ON lingxi_core.ai_interaction_session (conversation_id, user_id, application_version_id)
    WHERE status = 'PENDING';
CREATE INDEX IF NOT EXISTS idx_interaction_session_run
    ON lingxi_core.ai_interaction_session (run_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_interaction_session_application_version
    ON lingxi_core.ai_interaction_session (application_version_id, created_at DESC);
