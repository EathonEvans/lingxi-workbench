-- 知识索引版本只冻结已经完成向量化的分块任务，所有引用均为带索引的逻辑外键。
ALTER TABLE lingxi_core.ai_knowledge_base
    ADD COLUMN IF NOT EXISTS published_index_version_id BIGINT;
CREATE INDEX IF NOT EXISTS idx_ai_knowledge_base_published_index
    ON lingxi_core.ai_knowledge_base (published_index_version_id);

CREATE TABLE IF NOT EXISTS lingxi_core.ai_knowledge_index_version
(
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    knowledge_base_id           BIGINT      NOT NULL,
    version_no                  INTEGER     NOT NULL,
    embedding_model_instance_id BIGINT      NOT NULL,
    embedding_dimension         INTEGER     NOT NULL,
    distance_type               VARCHAR(16) NOT NULL,
    content_checksum            VARCHAR(64) NOT NULL,
    chunk_count                 INTEGER     NOT NULL,
    published_by                BIGINT      NOT NULL,
    published_at                TIMESTAMPTZ NOT NULL,
    created_at                  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_knowledge_index_version_no UNIQUE (knowledge_base_id, version_no),
    CONSTRAINT uk_knowledge_index_checksum UNIQUE (knowledge_base_id, content_checksum),
    CONSTRAINT ck_knowledge_index_version_no CHECK (version_no > 0),
    CONSTRAINT ck_knowledge_index_dimension CHECK (embedding_dimension > 0),
    CONSTRAINT ck_knowledge_index_distance CHECK (distance_type IN ('COSINE')),
    CONSTRAINT ck_knowledge_index_chunk_count CHECK (chunk_count > 0)
);
CREATE INDEX IF NOT EXISTS idx_knowledge_index_version_base
    ON lingxi_core.ai_knowledge_index_version (knowledge_base_id, version_no DESC);
CREATE INDEX IF NOT EXISTS idx_knowledge_index_version_model
    ON lingxi_core.ai_knowledge_index_version (embedding_model_instance_id);

CREATE TABLE IF NOT EXISTS lingxi_core.ai_knowledge_index_version_task
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    index_version_id BIGINT      NOT NULL,
    document_id      BIGINT      NOT NULL,
    chunk_task_id    BIGINT      NOT NULL,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_knowledge_index_version_document UNIQUE (index_version_id, document_id),
    CONSTRAINT uk_knowledge_index_version_task UNIQUE (index_version_id, chunk_task_id)
);
CREATE INDEX IF NOT EXISTS idx_knowledge_index_task_version
    ON lingxi_core.ai_knowledge_index_version_task (index_version_id, chunk_task_id);
CREATE INDEX IF NOT EXISTS idx_knowledge_index_task_task
    ON lingxi_core.ai_knowledge_index_version_task (chunk_task_id);

ALTER TABLE lingxi_core.ai_agent_version_knowledge
    ADD COLUMN IF NOT EXISTS knowledge_index_version_id BIGINT;
CREATE INDEX IF NOT EXISTS idx_agent_version_knowledge_index
    ON lingxi_core.ai_agent_version_knowledge (knowledge_index_version_id);

ALTER TABLE lingxi_core.ai_agent_draft
    ALTER COLUMN schema_version SET DEFAULT 4;

COMMENT ON COLUMN lingxi_core.ai_agent.agent_type IS
    'Agent类型：REACT通用推理执行，RAG_CHAT历史知识问答，SUPERVISOR历史多Agent监督者';

COMMIT;
