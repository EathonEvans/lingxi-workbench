BEGIN;

-- workflow 主表：身份信息和发布状态
CREATE TABLE IF NOT EXISTS lingxi_core.ai_workflow
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                 VARCHAR(64)  NOT NULL,
    code                 VARCHAR(64)  NOT NULL,
    description          VARCHAR(500),
    status               VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    published_version_id BIGINT,
    created_by           BIGINT       NOT NULL,
    updated_by           BIGINT       NOT NULL,
    created_at           TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_ai_workflow_code UNIQUE (code),
    CONSTRAINT ck_ai_workflow_code CHECK (code = LOWER(BTRIM(code))),
    CONSTRAINT ck_ai_workflow_status CHECK (status IN ('ACTIVE', 'DISABLED'))
);

-- workflow 草稿：可编辑的 workflow 定义，revision 乐观锁防并发
CREATE TABLE IF NOT EXISTS lingxi_core.ai_workflow_draft
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workflow_id      BIGINT       NOT NULL,
    base_version_id  BIGINT,
    schema_version   INTEGER      NOT NULL DEFAULT 1,
    definition       JSONB        NOT NULL,
    revision         BIGINT       NOT NULL DEFAULT 0,
    change_note      VARCHAR(255),
    created_by       BIGINT       NOT NULL,
    updated_by       BIGINT       NOT NULL,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_ai_workflow_draft_workflow UNIQUE (workflow_id),
    CONSTRAINT ck_ai_workflow_draft_schema CHECK (schema_version > 0),
    CONSTRAINT ck_ai_workflow_draft_revision CHECK (revision >= 0)
);

-- workflow 发布版本：不可变快照
CREATE TABLE IF NOT EXISTS lingxi_core.ai_workflow_version
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workflow_id         BIGINT       NOT NULL,
    version_no          INTEGER      NOT NULL,
    version_name        VARCHAR(64)  NOT NULL,
    schema_version      INTEGER      NOT NULL,
    definition_snapshot JSONB        NOT NULL,
    snapshot_checksum   VARCHAR(64)  NOT NULL,
    change_note         VARCHAR(255),
    published_by        BIGINT       NOT NULL,
    published_at        TIMESTAMPTZ  NOT NULL,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_ai_workflow_version_no UNIQUE (workflow_id, version_no),
    CONSTRAINT uk_ai_workflow_version_snapshot
        UNIQUE (workflow_id, snapshot_checksum),
    CONSTRAINT ck_ai_workflow_version_no CHECK (version_no > 0),
    CONSTRAINT ck_ai_workflow_version_schema CHECK (schema_version > 0)
);
CREATE INDEX IF NOT EXISTS idx_ai_workflow_version_workflow
    ON lingxi_core.ai_workflow_version (workflow_id, version_no DESC);

-- 关联字段均为逻辑外键，存在性、归属和生命周期由 Workflow Service 校验。
CREATE INDEX IF NOT EXISTS idx_ai_workflow_published_version
    ON lingxi_core.ai_workflow (published_version_id);
CREATE INDEX IF NOT EXISTS idx_ai_workflow_draft_base_version
    ON lingxi_core.ai_workflow_draft (base_version_id);

