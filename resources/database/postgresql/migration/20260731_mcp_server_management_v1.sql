BEGIN;

-- MCP Server 保存动态连接配置；Bearer Token 复用应用主密钥加密，不保存明文。
-- 当前阶段仅发现远端工具，不与 ai_tool 建立关联，因此不创建物理外键。
CREATE TABLE IF NOT EXISTS lingxi_core.ai_mcp_server
(
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                    VARCHAR(64)  NOT NULL,
    code                    VARCHAR(64)  NOT NULL,
    description             VARCHAR(500),
    transport_type          VARCHAR(32)  NOT NULL,
    base_url                VARCHAR(500) NOT NULL,
    endpoint                VARCHAR(255) NOT NULL DEFAULT '/mcp',
    authentication_type     VARCHAR(32)  NOT NULL DEFAULT 'NONE',
    secret_ciphertext       TEXT,
    secret_iv               VARCHAR(64),
    secret_hint             VARCHAR(32),
    request_timeout_seconds INTEGER      NOT NULL DEFAULT 20,
    status                  VARCHAR(16)  NOT NULL DEFAULT 'DISABLED',
    last_test_status        VARCHAR(16)  NOT NULL DEFAULT 'UNTESTED',
    last_test_latency_ms    INTEGER,
    last_test_error_code    VARCHAR(64),
    last_test_message       VARCHAR(255) NOT NULL DEFAULT '尚未测试连接',
    last_test_at            TIMESTAMPTZ,
    created_by              BIGINT       NOT NULL,
    updated_by              BIGINT       NOT NULL,
    created_at              TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_ai_mcp_server_code UNIQUE (code),
    CONSTRAINT ck_ai_mcp_server_code CHECK (code = LOWER(BTRIM(code))),
    CONSTRAINT ck_ai_mcp_server_timeout CHECK (request_timeout_seconds BETWEEN 1 AND 60),
    CONSTRAINT ck_ai_mcp_server_secret CHECK (
        (authentication_type = 'NONE' AND secret_ciphertext IS NULL AND secret_iv IS NULL)
        OR (authentication_type <> 'NONE' AND secret_ciphertext IS NOT NULL AND secret_iv IS NOT NULL)
    )
);

CREATE INDEX IF NOT EXISTS idx_ai_mcp_server_status
    ON lingxi_core.ai_mcp_server (status, updated_at DESC);

COMMENT ON TABLE lingxi_core.ai_mcp_server
    IS 'MCP Server动态连接配置；第一阶段用于连接测试和远端工具发现';
COMMENT ON COLUMN lingxi_core.ai_mcp_server.transport_type
    IS 'MCP传输协议；第一阶段仅开放STREAMABLE_HTTP';
COMMENT ON COLUMN lingxi_core.ai_mcp_server.secret_ciphertext
    IS 'Bearer Token密文；接口和日志均不得返回';
COMMENT ON COLUMN lingxi_core.ai_mcp_server.last_test_status
    IS '最近一次真实initialize和tools/list测试状态';

INSERT INTO lingxi_core.sys_menu
    (parent_id, name, code, menu_type, route_path, component, icon, permission_code, sort_order, visible, status)
SELECT parent.id, 'MCP服务', 'MCP_SERVER_LIST', 'MENU', '/agent/mcp-server',
       'mcp-server/index', 'ri:server-line', 'mcp-server:list', 30, TRUE, 'ACTIVE'
FROM lingxi_core.sys_menu parent
WHERE parent.code = 'AGENT'
ON CONFLICT (code) DO UPDATE
SET parent_id = EXCLUDED.parent_id,
    name = EXCLUDED.name,
    route_path = EXCLUDED.route_path,
    component = EXCLUDED.component,
    icon = EXCLUDED.icon,
    permission_code = EXCLUDED.permission_code,
    sort_order = EXCLUDED.sort_order,
    visible = TRUE,
    status = 'ACTIVE';

INSERT INTO lingxi_core.sys_menu
    (parent_id, name, code, menu_type, permission_code, sort_order, visible, status)
SELECT parent.id, 'MCP服务维护', 'MCP_SERVER_MANAGE', 'BUTTON', 'mcp-server:manage', 10, FALSE, 'ACTIVE'
FROM lingxi_core.sys_menu parent
WHERE parent.code = 'MCP_SERVER_LIST'
ON CONFLICT (code) DO UPDATE
SET parent_id = EXCLUDED.parent_id,
    name = EXCLUDED.name,
    permission_code = EXCLUDED.permission_code,
    sort_order = EXCLUDED.sort_order,
    visible = FALSE,
    status = 'ACTIVE';

COMMIT;
