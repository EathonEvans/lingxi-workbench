-- 知识库和文档解析V1：本阶段止于解析正文入库，不创建切片、向量或检索表。
CREATE TABLE IF NOT EXISTS lingxi_core.ai_knowledge_base
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(64)  NOT NULL,
    code        VARCHAR(64)  NOT NULL,
    description VARCHAR(500),
    status      VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    created_by  BIGINT       NOT NULL,
    updated_by  BIGINT       NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_ai_knowledge_base_code UNIQUE (code),
    CONSTRAINT ck_ai_knowledge_base_code CHECK (code = LOWER(BTRIM(code)))
);

CREATE TABLE IF NOT EXISTS lingxi_core.ai_knowledge_document
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    knowledge_base_id   BIGINT        NOT NULL,
    name                VARCHAR(128)  NOT NULL,
    source_type         VARCHAR(16)   NOT NULL,
    file_name           VARCHAR(255)  NOT NULL,
    file_type           VARCHAR(32)   NOT NULL,
    file_size           BIGINT        NOT NULL,
    object_key          VARCHAR(500)  NOT NULL,
    content_hash        VARCHAR(64)   NOT NULL,
    status              VARCHAR(16)   NOT NULL DEFAULT 'UPLOADED',
    page_count          INTEGER,
    parsed_content      TEXT,
    parsed_content_hash VARCHAR(64),
    error_code          VARCHAR(64),
    error_message       VARCHAR(500),
    parsed_at           TIMESTAMPTZ,
    created_by          BIGINT        NOT NULL,
    updated_by          BIGINT        NOT NULL,
    created_at          TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_ai_knowledge_document_base
        FOREIGN KEY (knowledge_base_id) REFERENCES lingxi_core.ai_knowledge_base (id),
    CONSTRAINT uk_ai_knowledge_document_hash UNIQUE (knowledge_base_id, content_hash),
    CONSTRAINT uk_ai_knowledge_document_object_key UNIQUE (object_key),
    CONSTRAINT ck_ai_knowledge_document_file_size CHECK (file_size >= 0),
    CONSTRAINT ck_ai_knowledge_document_page_count CHECK (page_count IS NULL OR page_count > 0)
);
CREATE INDEX IF NOT EXISTS idx_ai_knowledge_document_base_status
    ON lingxi_core.ai_knowledge_document (knowledge_base_id, status, created_at DESC);

CREATE TABLE IF NOT EXISTS lingxi_core.ai_knowledge_ingestion_job
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    knowledge_base_id BIGINT       NOT NULL,
    document_id       BIGINT       NOT NULL,
    status            VARCHAR(16)  NOT NULL DEFAULT 'PENDING',
    progress          INTEGER      NOT NULL DEFAULT 0,
    retry_count       INTEGER      NOT NULL DEFAULT 0,
    error_code        VARCHAR(64),
    error_message     VARCHAR(500),
    started_at        TIMESTAMPTZ,
    finished_at       TIMESTAMPTZ,
    created_by        BIGINT       NOT NULL,
    updated_by        BIGINT       NOT NULL,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_ai_knowledge_job_base
        FOREIGN KEY (knowledge_base_id) REFERENCES lingxi_core.ai_knowledge_base (id),
    CONSTRAINT fk_ai_knowledge_job_document
        FOREIGN KEY (document_id) REFERENCES lingxi_core.ai_knowledge_document (id) ON DELETE CASCADE,
    CONSTRAINT ck_ai_knowledge_job_progress CHECK (progress BETWEEN 0 AND 100),
    CONSTRAINT ck_ai_knowledge_job_retry_count CHECK (retry_count >= 0)
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_ai_knowledge_job_active
    ON lingxi_core.ai_knowledge_ingestion_job (document_id)
    WHERE status IN ('PENDING', 'RUNNING');
CREATE INDEX IF NOT EXISTS idx_ai_knowledge_job_document
    ON lingxi_core.ai_knowledge_ingestion_job (document_id, created_at DESC);

