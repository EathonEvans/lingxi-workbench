-- 灵析 AI Workbench 第一版数据库结构初始化脚本。
-- 本文件只维护扩展、Schema、表、索引和约束，不写入业务数据。

CREATE EXTENSION IF NOT EXISTS vector;

CREATE SCHEMA IF NOT EXISTS lingxi_core;
CREATE SCHEMA IF NOT EXISTS lingxi_vector;
CREATE SCHEMA IF NOT EXISTS lingxi_audit;

CREATE TABLE IF NOT EXISTS lingxi_core.user_account
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(64)  NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    display_name  VARCHAR(64)  NOT NULL,
    avatar_url    VARCHAR(512),
    status        VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_user_account_username_normalized
        CHECK (username = LOWER(BTRIM(username))),
    CONSTRAINT ck_user_account_status
        CHECK (status IN ('ACTIVE', 'DISABLED'))
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_user_account_username
    ON lingxi_core.user_account (username);

COMMENT ON TABLE lingxi_core.user_account IS '由管理端分配和管理的用户账号';
COMMENT ON COLUMN lingxi_core.user_account.password_hash IS 'BCrypt 密码哈希，禁止存储明文密码';

CREATE TABLE IF NOT EXISTS lingxi_core.admin_account
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(64)  NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    display_name  VARCHAR(64)  NOT NULL,
    avatar_url    VARCHAR(512),
    status        VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_admin_account_username_normalized
        CHECK (username = LOWER(BTRIM(username))),
    CONSTRAINT ck_admin_account_status
        CHECK (status IN ('ACTIVE', 'DISABLED'))
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_admin_account_username
    ON lingxi_core.admin_account (username);

COMMENT ON TABLE lingxi_core.admin_account IS '管理端登录账号';
COMMENT ON COLUMN lingxi_core.admin_account.password_hash IS 'BCrypt 密码哈希，禁止存储明文密码';
