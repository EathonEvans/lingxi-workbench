CREATE INDEX IF NOT EXISTS idx_sys_role_department_department
    ON lingxi_core.sys_role_department (department_id);

-- 模型供应商只保存协议和连接地址，不保存任何密钥。
CREATE TABLE IF NOT EXISTS lingxi_core.ai_model_provider
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(64)  NOT NULL,
    code       VARCHAR(64)  NOT NULL,
    protocol   VARCHAR(32)  NOT NULL DEFAULT 'OPENAI_COMPATIBLE',
    base_url   VARCHAR(512) NOT NULL,
    status     VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    remark     VARCHAR(255),
    created_by BIGINT       NOT NULL,
    updated_by BIGINT       NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_ai_model_provider_code UNIQUE (code),
    CONSTRAINT ck_ai_model_provider_code CHECK (code = LOWER(BTRIM(code))),
    CONSTRAINT ck_ai_model_provider_protocol CHECK (protocol IN ('OPENAI_COMPATIBLE'))
);

-- 模型密钥使用AES-256-GCM加密，主密钥由部署环境提供。
CREATE TABLE IF NOT EXISTS lingxi_core.ai_model_credential
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_id       BIGINT       NOT NULL,
    name              VARCHAR(64)  NOT NULL,
    secret_ciphertext TEXT,
    secret_iv         VARCHAR(64),
    secret_hint       VARCHAR(32)  NOT NULL,
    status            VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    rotated_at        TIMESTAMPTZ,
    created_by        BIGINT       NOT NULL,
    updated_by        BIGINT       NOT NULL,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_ai_model_credential_name UNIQUE (provider_id, name),
    CONSTRAINT ck_ai_model_credential_secret CHECK (
        (status = 'REVOKED' AND secret_ciphertext IS NULL AND secret_iv IS NULL)
        OR (status <> 'REVOKED' AND secret_ciphertext IS NOT NULL AND secret_iv IS NOT NULL)
    )
);

CREATE INDEX IF NOT EXISTS idx_ai_model_credential_provider
    ON lingxi_core.ai_model_credential (provider_id);

-- 模型实例是业务稳定引用和运行时实际调用的最小配置单元。
CREATE TABLE IF NOT EXISTS lingxi_core.ai_model_instance
(
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_id            BIGINT       NOT NULL,
    credential_id          BIGINT       NOT NULL,
    name                   VARCHAR(64)  NOT NULL,
    code                   VARCHAR(64)  NOT NULL,
    model_code             VARCHAR(128) NOT NULL,
    model_type             VARCHAR(32)  NOT NULL DEFAULT 'CHAT',
    capabilities           JSONB        NOT NULL DEFAULT '[]'::JSONB,
    temperature            NUMERIC(4, 3),
    top_p                  NUMERIC(4, 3),
    max_tokens             INTEGER,
    context_window         INTEGER,
    stop_sequences         JSONB        NOT NULL DEFAULT '[]'::JSONB,
    extension_parameters   JSONB        NOT NULL DEFAULT '{}'::JSONB,
    timeout_seconds        INTEGER      NOT NULL DEFAULT 60,
    max_retries            INTEGER      NOT NULL DEFAULT 1,
    is_default             BOOLEAN      NOT NULL DEFAULT FALSE,
    status                 VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    last_test_status       VARCHAR(16)  NOT NULL DEFAULT 'UNTESTED',
    last_test_latency_ms   INTEGER,
    last_test_error_code   VARCHAR(64),
    last_test_message      VARCHAR(255),
    last_test_at           TIMESTAMPTZ,
    created_by             BIGINT       NOT NULL,
    updated_by             BIGINT       NOT NULL,
    created_at             TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at             TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_ai_model_instance_code UNIQUE (code),
    CONSTRAINT ck_ai_model_instance_temperature CHECK (temperature IS NULL OR temperature BETWEEN 0 AND 2),
    CONSTRAINT ck_ai_model_instance_top_p CHECK (top_p IS NULL OR top_p BETWEEN 0 AND 1),
    CONSTRAINT ck_ai_model_instance_extension_parameters CHECK (
        jsonb_typeof(extension_parameters) = 'object'
    ),
    CONSTRAINT ck_ai_model_instance_limits CHECK (
        (max_tokens IS NULL OR max_tokens > 0)
        AND (context_window IS NULL OR context_window > 0)
        AND timeout_seconds > 0
        AND max_retries BETWEEN 0 AND 2
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_ai_model_instance_default_type
    ON lingxi_core.ai_model_instance (model_type)
    WHERE is_default = TRUE;
CREATE INDEX IF NOT EXISTS idx_ai_model_instance_available
    ON lingxi_core.ai_model_instance (model_type, status, last_test_status);
CREATE INDEX IF NOT EXISTS idx_ai_model_instance_provider
    ON lingxi_core.ai_model_instance (provider_id);
CREATE INDEX IF NOT EXISTS idx_ai_model_instance_credential
    ON lingxi_core.ai_model_instance (credential_id);

-- Prompt主记录维护稳定编码、启停状态和当前正式版本指针。
CREATE TABLE IF NOT EXISTS lingxi_core.ai_prompt
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                 VARCHAR(64)  NOT NULL,
    code                 VARCHAR(64)  NOT NULL,
