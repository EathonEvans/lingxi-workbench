ALTER TABLE lingxi_core.sys_user ADD COLUMN IF NOT EXISTS email VARCHAR(254);
ALTER TABLE lingxi_core.sys_user ADD COLUMN IF NOT EXISTS mobile VARCHAR(32);
ALTER TABLE lingxi_core.sys_user ADD COLUMN IF NOT EXISTS department_id BIGINT;

