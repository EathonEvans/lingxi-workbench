-- 灵析 AI Workbench 第一版数据库结构初始化脚本。
-- 本文件只维护扩展、Schema、表、索引和约束，不写入业务数据。

CREATE EXTENSION IF NOT EXISTS vector;

CREATE SCHEMA IF NOT EXISTS lingxi_core;
CREATE SCHEMA IF NOT EXISTS lingxi_vector;
CREATE SCHEMA IF NOT EXISTS lingxi_audit;

CREATE TABLE IF NOT EXISTS lingxi_core.user_account
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(64)  NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    display_name  VARCHAR(64)  NOT NULL,
    avatar_url    VARCHAR(512),
    status        VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_user_account_username_normalized
        CHECK (username = LOWER(BTRIM(username))),
    CONSTRAINT ck_user_account_status
        CHECK (status IN ('ACTIVE', 'DISABLED'))
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_user_account_username
    ON lingxi_core.user_account (username);

COMMENT ON TABLE lingxi_core.user_account IS '由管理端分配和管理的用户账号';
COMMENT ON COLUMN lingxi_core.user_account.password_hash IS 'BCrypt 密码哈希，禁止存储明文密码';

CREATE TABLE IF NOT EXISTS lingxi_core.admin_account
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(64)  NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    display_name  VARCHAR(64)  NOT NULL,
    avatar_url    VARCHAR(512),
    status        VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_admin_account_username_normalized
        CHECK (username = LOWER(BTRIM(username))),
    CONSTRAINT ck_admin_account_status
        CHECK (status IN ('ACTIVE', 'DISABLED'))
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_admin_account_username
    ON lingxi_core.admin_account (username);

COMMENT ON TABLE lingxi_core.admin_account IS '管理端登录账号';
COMMENT ON COLUMN lingxi_core.admin_account.password_hash IS 'BCrypt 密码哈希，禁止存储明文密码';

-- 部门树是管理端数据权限的基础，第一版一个管理员只归属一个主部门。
CREATE TABLE IF NOT EXISTS lingxi_core.admin_department
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id   BIGINT,
    name        VARCHAR(64)  NOT NULL,
    code        VARCHAR(64)  NOT NULL,
    sort_order  INTEGER      NOT NULL DEFAULT 0,
    status      VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_admin_department_parent
        FOREIGN KEY (parent_id) REFERENCES lingxi_core.admin_department (id),
    CONSTRAINT ck_admin_department_status
        CHECK (status IN ('ACTIVE', 'DISABLED'))
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_admin_department_code
    ON lingxi_core.admin_department (code);
CREATE INDEX IF NOT EXISTS idx_admin_department_parent
    ON lingxi_core.admin_department (parent_id);

COMMENT ON TABLE lingxi_core.admin_department IS '公司部门树';
COMMENT ON COLUMN lingxi_core.admin_department.code IS '稳定的部门编码，不随部门名称修改';

-- 旧库重复执行脚本时，通过 ADD COLUMN IF NOT EXISTS 安全补齐所属部门字段。
ALTER TABLE lingxi_core.admin_account
    ADD COLUMN IF NOT EXISTS department_id BIGINT;

DO
$$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'fk_admin_account_department'
          AND conrelid = 'lingxi_core.admin_account'::REGCLASS
    ) THEN
        ALTER TABLE lingxi_core.admin_account
            ADD CONSTRAINT fk_admin_account_department
                FOREIGN KEY (department_id) REFERENCES lingxi_core.admin_department (id);
    END IF;
END
$$;

CREATE INDEX IF NOT EXISTS idx_admin_account_department
    ON lingxi_core.admin_account (department_id);

-- 角色同时承载功能权限和数据范围。
CREATE TABLE IF NOT EXISTS lingxi_core.admin_role
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(64)  NOT NULL,
    code        VARCHAR(64)  NOT NULL,
    data_scope  VARCHAR(32)  NOT NULL DEFAULT 'SELF',
    sort_order  INTEGER      NOT NULL DEFAULT 0,
    built_in    BOOLEAN      NOT NULL DEFAULT FALSE,
    status      VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    remark      VARCHAR(255),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_admin_role_data_scope
        CHECK (data_scope IN ('ALL', 'DEPARTMENT_AND_CHILDREN', 'DEPARTMENT', 'SELF', 'CUSTOM')),
    CONSTRAINT ck_admin_role_status
        CHECK (status IN ('ACTIVE', 'DISABLED'))
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_admin_role_code
    ON lingxi_core.admin_role (code);

COMMENT ON TABLE lingxi_core.admin_role IS '管理端角色';
COMMENT ON COLUMN lingxi_core.admin_role.data_scope IS '角色数据范围';
COMMENT ON COLUMN lingxi_core.admin_role.built_in IS '内置角色不允许删除';

-- 菜单同时表达前端导航和后端权限码，最终访问控制以 permission_code 为准。
CREATE TABLE IF NOT EXISTS lingxi_core.admin_menu
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id        BIGINT,
    name             VARCHAR(64)  NOT NULL,
    code             VARCHAR(64)  NOT NULL,
    menu_type        VARCHAR(16)  NOT NULL,
    route_path       VARCHAR(255),
    component        VARCHAR(255),
    icon             VARCHAR(128),
    permission_code  VARCHAR(128),
    sort_order       INTEGER      NOT NULL DEFAULT 0,
    visible          BOOLEAN      NOT NULL DEFAULT TRUE,
    status           VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_admin_menu_parent
        FOREIGN KEY (parent_id) REFERENCES lingxi_core.admin_menu (id),
    CONSTRAINT ck_admin_menu_type
        CHECK (menu_type IN ('DIRECTORY', 'MENU', 'BUTTON')),
    CONSTRAINT ck_admin_menu_status
        CHECK (status IN ('ACTIVE', 'DISABLED'))
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_admin_menu_code
    ON lingxi_core.admin_menu (code);
CREATE UNIQUE INDEX IF NOT EXISTS uk_admin_menu_permission_code
    ON lingxi_core.admin_menu (permission_code)
    WHERE permission_code IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_admin_menu_parent
    ON lingxi_core.admin_menu (parent_id);

COMMENT ON TABLE lingxi_core.admin_menu IS '管理端目录、菜单和按钮权限';
COMMENT ON COLUMN lingxi_core.admin_menu.permission_code IS '后端接口和前端按钮共用的权限标识';

CREATE TABLE IF NOT EXISTS lingxi_core.admin_account_role
(
    account_id BIGINT NOT NULL,
    role_id    BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (account_id, role_id),
    CONSTRAINT fk_admin_account_role_account
        FOREIGN KEY (account_id) REFERENCES lingxi_core.admin_account (id) ON DELETE CASCADE,
    CONSTRAINT fk_admin_account_role_role
        FOREIGN KEY (role_id) REFERENCES lingxi_core.admin_role (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_admin_account_role_role
    ON lingxi_core.admin_account_role (role_id);

CREATE TABLE IF NOT EXISTS lingxi_core.admin_role_menu
(
    role_id    BIGINT NOT NULL,
    menu_id    BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (role_id, menu_id),
    CONSTRAINT fk_admin_role_menu_role
        FOREIGN KEY (role_id) REFERENCES lingxi_core.admin_role (id) ON DELETE CASCADE,
    CONSTRAINT fk_admin_role_menu_menu
        FOREIGN KEY (menu_id) REFERENCES lingxi_core.admin_menu (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_admin_role_menu_menu
    ON lingxi_core.admin_role_menu (menu_id);

CREATE TABLE IF NOT EXISTS lingxi_core.admin_role_department
(
    role_id       BIGINT NOT NULL,
    department_id BIGINT NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (role_id, department_id),
    CONSTRAINT fk_admin_role_department_role
        FOREIGN KEY (role_id) REFERENCES lingxi_core.admin_role (id) ON DELETE CASCADE,
    CONSTRAINT fk_admin_role_department_department
        FOREIGN KEY (department_id) REFERENCES lingxi_core.admin_department (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_admin_role_department_department
    ON lingxi_core.admin_role_department (department_id);
