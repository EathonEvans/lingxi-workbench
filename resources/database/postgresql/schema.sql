-- 兼容已执行过旧版建表脚本的开发数据库，历史Prompt统一归类为系统角色。
ALTER TABLE lingxi_core.ai_prompt
    ADD COLUMN IF NOT EXISTS role VARCHAR(16) NOT NULL DEFAULT 'SYSTEM';

-- Prompt版本保存不可变的已发布内容；同一个Prompt同时最多只有一个草稿。
CREATE TABLE IF NOT EXISTS lingxi_core.ai_prompt_version
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prompt_id      BIGINT       NOT NULL,
    version_no     INTEGER      NOT NULL,
    prompt_content TEXT         NOT NULL,
    variables      JSONB        NOT NULL DEFAULT '[]'::JSONB,
    status         VARCHAR(16)  NOT NULL DEFAULT 'DRAFT',
    change_note    VARCHAR(255),
    published_at   TIMESTAMPTZ,
    created_by     BIGINT       NOT NULL,
    updated_by     BIGINT       NOT NULL,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_ai_prompt_version_no UNIQUE (prompt_id, version_no),
    CONSTRAINT ck_ai_prompt_version_no CHECK (version_no > 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_ai_prompt_version_draft
    ON lingxi_core.ai_prompt_version (prompt_id)
    WHERE status = 'DRAFT';
CREATE INDEX IF NOT EXISTS idx_ai_prompt_version_prompt
    ON lingxi_core.ai_prompt_version (prompt_id, version_no DESC);

CREATE INDEX IF NOT EXISTS idx_ai_prompt_published_version
    ON lingxi_core.ai_prompt (published_version_id)
    WHERE published_version_id IS NOT NULL;

-- 业务领域树只承担控制面筛选与发布校验，不参与运行时动态资源发现。
CREATE TABLE IF NOT EXISTS lingxi_core.ai_domain
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id   BIGINT,
    root_id     BIGINT,
    name        VARCHAR(64)  NOT NULL,
    code        VARCHAR(64)  NOT NULL,
    description VARCHAR(500),
    depth       INTEGER      NOT NULL,
    sort_order  INTEGER      NOT NULL DEFAULT 0,
    status      VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    created_by  BIGINT       NOT NULL,
    updated_by  BIGINT       NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_ai_domain_code UNIQUE (code),
    CONSTRAINT ck_ai_domain_code CHECK (code = LOWER(BTRIM(code))),
    CONSTRAINT ck_ai_domain_depth CHECK (depth BETWEEN 1 AND 3),
    CONSTRAINT ck_ai_domain_status CHECK (status IN ('ACTIVE', 'DISABLED'))
);
CREATE INDEX IF NOT EXISTS idx_ai_domain_parent ON lingxi_core.ai_domain (parent_id, sort_order, id);
CREATE INDEX IF NOT EXISTS idx_ai_domain_root ON lingxi_core.ai_domain (root_id, depth, status);

-- Agent 控制面：稳定身份、可编辑草稿和不可变发布版本相互分离。
