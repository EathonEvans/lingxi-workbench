-- 草稿绑定知识库及其 Embedding 模型，发布时再冻结不可变知识索引版本。
CREATE TABLE IF NOT EXISTS lingxi_core.ai_agent_draft_knowledge
(
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
