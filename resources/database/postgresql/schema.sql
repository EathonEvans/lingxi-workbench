CREATE INDEX IF NOT EXISTS idx_ai_agent_published_version
    ON lingxi_core.ai_agent (published_version_id);
CREATE INDEX IF NOT EXISTS idx_ai_agent_domain
    ON lingxi_core.ai_agent (domain_id, role, status);

-- Tool 控制面定义：运行端执行器按 code 注册，数据库不保存可执行代码。
CREATE TABLE IF NOT EXISTS lingxi_core.ai_tool
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(64)   NOT NULL,
    code             VARCHAR(64)   NOT NULL,
    description      VARCHAR(1000) NOT NULL,
    source_type      VARCHAR(32)   NOT NULL DEFAULT 'LOCAL_FUNCTION',
    mcp_server_id    BIGINT,
    remote_tool_name VARCHAR(128),
    parameter_schema JSONB         NOT NULL DEFAULT '{"type":"object","properties":{}}'::JSONB,
    risk_level      VARCHAR(16)   NOT NULL DEFAULT 'LOW',
    approval_required BOOLEAN     NOT NULL DEFAULT FALSE,
    approval_ttl_seconds INTEGER  NOT NULL DEFAULT 1800,
    resource_scope VARCHAR(255)   NOT NULL DEFAULT '当前会话授权范围',
    status           VARCHAR(16)   NOT NULL DEFAULT 'DISABLED',
    created_by       BIGINT        NOT NULL,
    updated_by       BIGINT        NOT NULL,
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_ai_tool_code UNIQUE (code),
    CONSTRAINT ck_ai_tool_code CHECK (code = LOWER(BTRIM(code))),
    CONSTRAINT ck_ai_tool_source_type CHECK (source_type IN ('LOCAL_FUNCTION', 'MCP')),
    CONSTRAINT ck_ai_tool_parameter_schema CHECK (jsonb_typeof(parameter_schema) = 'object'),
    CONSTRAINT ck_ai_tool_status CHECK (status IN ('ACTIVE', 'DISABLED'))
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_ai_tool_mcp_binding
    ON lingxi_core.ai_tool (mcp_server_id, remote_tool_name)
    WHERE mcp_server_id IS NOT NULL AND remote_tool_name IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_ai_tool_mcp_server
    ON lingxi_core.ai_tool (mcp_server_id)
    WHERE mcp_server_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS lingxi_core.ai_mcp_server
(
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                    VARCHAR(64)  NOT NULL,
    code                    VARCHAR(64)  NOT NULL,
    description             VARCHAR(500),
    transport_type          VARCHAR(32)  NOT NULL,
    base_url                VARCHAR(500) NOT NULL,
    endpoint                VARCHAR(255) NOT NULL DEFAULT '/mcp',
    authentication_type     VARCHAR(32)  NOT NULL DEFAULT 'NONE',
    secret_ciphertext       TEXT,
    secret_iv               VARCHAR(64),
    secret_hint             VARCHAR(32),
    request_timeout_seconds INTEGER      NOT NULL DEFAULT 20,
    status                  VARCHAR(16)  NOT NULL DEFAULT 'DISABLED',
    last_test_status        VARCHAR(16)  NOT NULL DEFAULT 'UNTESTED',
    last_test_latency_ms    INTEGER,
    last_test_error_code    VARCHAR(64),
    last_test_message       VARCHAR(255) NOT NULL DEFAULT '尚未测试连接',
    last_test_at            TIMESTAMPTZ,
    created_by              BIGINT       NOT NULL,
    updated_by              BIGINT       NOT NULL,
    created_at              TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_ai_mcp_server_code UNIQUE (code),
    CONSTRAINT ck_ai_mcp_server_code CHECK (code = LOWER(BTRIM(code))),
    CONSTRAINT ck_ai_mcp_server_timeout CHECK (request_timeout_seconds BETWEEN 1 AND 60),
    CONSTRAINT ck_ai_mcp_server_secret CHECK (
        (authentication_type = 'NONE' AND secret_ciphertext IS NULL AND secret_iv IS NULL)
        OR (authentication_type <> 'NONE' AND secret_ciphertext IS NOT NULL AND secret_iv IS NOT NULL)
    )
);

CREATE INDEX IF NOT EXISTS idx_ai_mcp_server_status
    ON lingxi_core.ai_mcp_server (status, updated_at DESC);

