    CONSTRAINT ck_ai_agent_code CHECK (code = LOWER(BTRIM(code))),
    CONSTRAINT ck_ai_agent_role CHECK (role IN ('SPECIALIST', 'SUPERVISOR')),
    CONSTRAINT ck_ai_agent_status CHECK (status IN ('ACTIVE', 'DISABLED'))
