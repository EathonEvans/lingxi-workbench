-- 灵析 AI Workbench 第一版数据库结构初始化脚本。
-- 本文件只维护扩展、Schema、表、索引和约束，不写入业务数据。

CREATE EXTENSION IF NOT EXISTS vector;

CREATE SCHEMA IF NOT EXISTS lingxi_core;
CREATE SCHEMA IF NOT EXISTS lingxi_vector;
CREATE SCHEMA IF NOT EXISTS lingxi_audit;

CREATE TABLE IF NOT EXISTS lingxi_core.sys_user
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(64)  NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    display_name  VARCHAR(64)  NOT NULL,
    avatar_url    VARCHAR(512),
    email         VARCHAR(254),
    mobile        VARCHAR(32),
    department_id BIGINT,
    status        VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_sys_user_username_normalized
        CHECK (username = LOWER(BTRIM(username))),
    CONSTRAINT ck_sys_user_status
        CHECK (status IN ('ACTIVE', 'DISABLED'))
);

ALTER TABLE lingxi_core.sys_user ADD COLUMN IF NOT EXISTS email VARCHAR(254);
ALTER TABLE lingxi_core.sys_user ADD COLUMN IF NOT EXISTS mobile VARCHAR(32);
ALTER TABLE lingxi_core.sys_user ADD COLUMN IF NOT EXISTS department_id BIGINT;

CREATE UNIQUE INDEX IF NOT EXISTS uk_sys_user_username ON lingxi_core.sys_user (username);
CREATE UNIQUE INDEX IF NOT EXISTS uk_sys_user_email ON lingxi_core.sys_user (LOWER(email)) WHERE email IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uk_sys_user_mobile ON lingxi_core.sys_user (mobile) WHERE mobile IS NOT NULL;

COMMENT ON TABLE lingxi_core.sys_user IS '管理端和应用端共用的统一账号主表';
COMMENT ON COLUMN lingxi_core.sys_user.password_hash IS 'BCrypt 密码哈希，禁止存储明文密码';

-- 部门树是管理端数据权限的基础，第一版一个管理员只归属一个主部门。
CREATE TABLE IF NOT EXISTS lingxi_core.sys_department
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id   BIGINT,
    name        VARCHAR(64)  NOT NULL,
    code        VARCHAR(64)  NOT NULL,
    sort_order  INTEGER      NOT NULL DEFAULT 0,
    status      VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_sys_department_parent
        FOREIGN KEY (parent_id) REFERENCES lingxi_core.sys_department (id),
    CONSTRAINT ck_sys_department_status
        CHECK (status IN ('ACTIVE', 'DISABLED'))
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_sys_department_code
    ON lingxi_core.sys_department (code);
CREATE INDEX IF NOT EXISTS idx_sys_department_parent
    ON lingxi_core.sys_department (parent_id);

COMMENT ON TABLE lingxi_core.sys_department IS '公司部门树';
COMMENT ON COLUMN lingxi_core.sys_department.code IS '稳定的部门编码，不随部门名称修改';

-- 旧库重复执行脚本时，通过 ADD COLUMN IF NOT EXISTS 安全补齐所属部门字段。
DO
$$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'fk_sys_user_department'
          AND conrelid = 'lingxi_core.sys_user'::REGCLASS
    ) THEN
        ALTER TABLE lingxi_core.sys_user
            ADD CONSTRAINT fk_sys_user_department
                FOREIGN KEY (department_id) REFERENCES lingxi_core.sys_department (id);
    END IF;
END
$$;

CREATE INDEX IF NOT EXISTS idx_sys_user_department
    ON lingxi_core.sys_user (department_id);

-- 应用端访问资格独立建表，后续可继续扩展额度、功能限制等应用侧属性。
CREATE TABLE IF NOT EXISTS lingxi_core.sys_user_application_access
(
    user_id       BIGINT PRIMARY KEY,
    enabled       BOOLEAN     NOT NULL DEFAULT FALSE,
    enabled_at    TIMESTAMPTZ,
    disabled_at   TIMESTAMPTZ,
    updated_by    BIGINT,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_sys_user_application_access_user
        FOREIGN KEY (user_id) REFERENCES lingxi_core.sys_user (id) ON DELETE CASCADE,
    CONSTRAINT fk_sys_user_application_access_operator
        FOREIGN KEY (updated_by) REFERENCES lingxi_core.sys_user (id)
);

COMMENT ON TABLE lingxi_core.sys_user_application_access IS '统一账号的应用端访问资格与扩展配置';

-- 账号及访问权限关键变更审计，仅追加不修改。
CREATE TABLE IF NOT EXISTS lingxi_audit.sys_user_change_log
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_user_id   BIGINT       NOT NULL,
    operator_user_id BIGINT       NOT NULL,
    action           VARCHAR(64)  NOT NULL,
    change_summary   VARCHAR(1000) NOT NULL,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_sys_user_change_log_target
        FOREIGN KEY (target_user_id) REFERENCES lingxi_core.sys_user (id),
    CONSTRAINT fk_sys_user_change_log_operator
        FOREIGN KEY (operator_user_id) REFERENCES lingxi_core.sys_user (id)
);

CREATE INDEX IF NOT EXISTS idx_sys_user_change_log_target
    ON lingxi_audit.sys_user_change_log (target_user_id, created_at DESC);

-- 角色同时承载功能权限和数据范围。
CREATE TABLE IF NOT EXISTS lingxi_core.sys_role
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(64)  NOT NULL,
    code        VARCHAR(64)  NOT NULL,
    data_scope  VARCHAR(32)  NOT NULL DEFAULT 'SELF',
    sort_order  INTEGER      NOT NULL DEFAULT 0,
    built_in    BOOLEAN      NOT NULL DEFAULT FALSE,
    status      VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    remark      VARCHAR(255),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_sys_role_data_scope
        CHECK (data_scope IN ('ALL', 'DEPARTMENT_AND_CHILDREN', 'DEPARTMENT', 'SELF', 'CUSTOM')),
    CONSTRAINT ck_sys_role_status
        CHECK (status IN ('ACTIVE', 'DISABLED'))
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_sys_role_code
    ON lingxi_core.sys_role (code);

COMMENT ON TABLE lingxi_core.sys_role IS '管理端角色';
COMMENT ON COLUMN lingxi_core.sys_role.data_scope IS '角色数据范围';
COMMENT ON COLUMN lingxi_core.sys_role.built_in IS '内置角色不允许删除';

-- 菜单同时表达前端导航和后端权限码，最终访问控制以 permission_code 为准。
CREATE TABLE IF NOT EXISTS lingxi_core.sys_menu
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id        BIGINT,
    name             VARCHAR(64)  NOT NULL,
    code             VARCHAR(64)  NOT NULL,
    menu_type        VARCHAR(16)  NOT NULL,
    route_path       VARCHAR(255),
    component        VARCHAR(255),
    icon             VARCHAR(128),
    permission_code  VARCHAR(128),
    sort_order       INTEGER      NOT NULL DEFAULT 0,
    visible          BOOLEAN      NOT NULL DEFAULT TRUE,
    status           VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_sys_menu_parent
        FOREIGN KEY (parent_id) REFERENCES lingxi_core.sys_menu (id),
    CONSTRAINT ck_sys_menu_type
        CHECK (menu_type IN ('DIRECTORY', 'MENU', 'BUTTON')),
    CONSTRAINT ck_sys_menu_root_type
        CHECK (parent_id IS NOT NULL OR menu_type = 'DIRECTORY'),
    CONSTRAINT ck_sys_menu_status
        CHECK (status IN ('ACTIVE', 'DISABLED'))
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_sys_menu_code
    ON lingxi_core.sys_menu (code);
CREATE UNIQUE INDEX IF NOT EXISTS uk_sys_menu_permission_code
    ON lingxi_core.sys_menu (permission_code)
    WHERE permission_code IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_sys_menu_parent
    ON lingxi_core.sys_menu (parent_id);

COMMENT ON TABLE lingxi_core.sys_menu IS '管理端目录、菜单和按钮权限';
COMMENT ON COLUMN lingxi_core.sys_menu.permission_code IS '后端接口和前端按钮共用的权限标识';

CREATE TABLE IF NOT EXISTS lingxi_core.sys_user_role
(
    user_id    BIGINT NOT NULL,
    role_id    BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_sys_user_role_user
        FOREIGN KEY (user_id) REFERENCES lingxi_core.sys_user (id) ON DELETE CASCADE,
    CONSTRAINT fk_sys_user_role_role
        FOREIGN KEY (role_id) REFERENCES lingxi_core.sys_role (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_sys_user_role_role
    ON lingxi_core.sys_user_role (role_id);

CREATE TABLE IF NOT EXISTS lingxi_core.sys_role_menu
(
    role_id    BIGINT NOT NULL,
    menu_id    BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (role_id, menu_id),
    CONSTRAINT fk_sys_role_menu_role
        FOREIGN KEY (role_id) REFERENCES lingxi_core.sys_role (id) ON DELETE CASCADE,
    CONSTRAINT fk_sys_role_menu_menu
        FOREIGN KEY (menu_id) REFERENCES lingxi_core.sys_menu (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_sys_role_menu_menu
    ON lingxi_core.sys_role_menu (menu_id);

CREATE TABLE IF NOT EXISTS lingxi_core.sys_role_department
(
    role_id       BIGINT NOT NULL,
    department_id BIGINT NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (role_id, department_id),
    CONSTRAINT fk_sys_role_department_role
        FOREIGN KEY (role_id) REFERENCES lingxi_core.sys_role (id) ON DELETE CASCADE,
    CONSTRAINT fk_sys_role_department_department
        FOREIGN KEY (department_id) REFERENCES lingxi_core.sys_department (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_sys_role_department_department
    ON lingxi_core.sys_role_department (department_id);
